public class Exercicio1 {
    static void main() {
 /*Crie variáveis para dois números inteiros de valor a = 10 e b = 3 e mostre na tela: soma, subtração, multiplicação, divisão e resto.*/

        int num1= 10, num2= 3;

        System.out.println("A soma do numero 1 com o numero 2 é = "+ (num1+num2));

        System.out.println("A subtração do numero 1 com o numero 2 é = "+ (num1-num2));

        System.out.println("A multiplicação do numero 1 com o numero 2 é = "+ (num1*num2));

        System.out.println("A divisão do numero 1 com o numero 2 é = "+ (num1/num2));

        System.out.println("O resto da divisão entre os numeros 1 e 2 é = "+ (num1%num2));
    }
}
